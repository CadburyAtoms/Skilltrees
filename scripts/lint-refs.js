// Quoted-literal presence in the engine ('x' or "x" or `x`).
function inEngine(lit) {
  return engine.includes(`"${lit}"`) || engine.includes(`'${lit}'`) || engine.includes("`" + lit + "`");
}

// Comment-stripped engine source, for checks that must mean "in CODE". The tree-section headers
// list every talent by name (that IS the iron-rule-3 ledger), so a raw inEngine() is satisfied by
// prose — which is how pass 5's name-keyed-wiring exemption went silently vacuous when the 2b
// migration deleted the last tree-talent name from code (2026-07-26: two adversary abilities
// whose cues promised "use the item to auto-resolve" had been dead since their name-key was
// deleted, and pass 5 kept exempting them on the strength of a comment).
// `stripComments` itself now lives in ./lib/strip-comments.js (2026-08-10, hygiene campaign wave
// 4A) — required back here so this file's behavior is unchanged; tests/harness.js's `codeOnly`
// is the same function, so a source-reading test and this linter always agree on what "code" means.
const engineCode = stripComments(engine);
/* Comments AND string contents replaced by spaces, byte offsets and line breaks preserved — so a
 * match index in the result still points at the same place in the original. `stripComments` above
 * rebuilds line-by-line and cannot be indexed back into the source; pass 11 needs both (it reads
 * object literals out of the ORIGINAL text at offsets found in the blanked copy).
 *
 * TEMPLATE-AWARE since 07-27y, and that is not a nicety — it was silently disabling this whole
 * file. The old scanner closed a backtick string at the FIRST backtick it saw, so a NESTED template
 * inside `${…}` (the engine has ~30, e.g.
 *     `…${a ? " strike" : `${x.name}'s hit`}…`
 * ) closed the OUTER template early, dumped the remaining string text into "code", and the next
 * apostrophe in prose ("the victim's healing") opened a runaway span that ate real code until the
 * next stray quote. Measured on register-skills.js: 116 runaway spans, 598 code lines (5.9%)
 * blanked to nothing. Every pass built on this helper — 11 (dead fields), 15 (isGM hooks), 16
 * (Region flags), 17 (object-as-scalar) — was blind on those lines, and the hole was invisible
 * because a blind pass reports SUCCESS. Verified by the very bug that exposed it: pass 17 did not
 * see the third object-as-scalar site (register-skills.js:5933) until this was fixed.
 *
 * The scanner is now an explicit context stack: code / quoted-string / template, with `${…}`
 * pushing a fresh CODE frame (brace-counted) so nested templates and the code inside interpolations
 * are both handled. Code inside `${…}` is now EXPOSED to the passes, which is correct — it is code.
 *
 * REGEX LITERALS get the standard prev-token heuristic: a `/` starts a regex when the previous
 * non-space code character cannot end an expression. Without it, `/[&<>"]/` (escCw, one line) opened
 * a fake string on its `"` and swallowed the next 36 lines. The heuristic is not a tokeniser — it
 * mis-reads `a /b/ c` as a regex — but that is division by an identifier on both sides, which does
 * not occur here, and the failure direction is the safe one (blanking too much never invents a
 * violation, it only hides one, and the per-pass rot alarms catch a collapse). */
/* Does the `/` at `i` open a REGEX literal (rather than being division)? The standard heuristic:
 * look back past whitespace at the previous code character — if it cannot END an expression, a
 * regex must follow. `)` is deliberately treated as "can end" (so `(a+b) / c` is division), which
 * mis-reads `if (x) /re/.test(y)`; no such form exists here. */
function regexStartsHere(src, i) {
  let j = i - 1;
  while (j >= 0 && /\s/.test(src[j])) j--;
  if (j < 0) return true;
  const p = src[j];
  if ("([{,;:=!&|?+-*%~^<>".includes(p)) return true;
  return /\b(return|typeof|case|in|of|new|delete|void|do|else|yield|await)$/.test(src.slice(Math.max(0, j - 9), j + 1));
}
function blankStringsAndComments(src, { keepStrings = false } = {}) {
  let out = "";
  const emit = (ch, blankIt) => { out += (ch === "\n") ? "\n" : (blankIt ? " " : ch); };
  const stack = [{ k: "code", braces: 0, root: true }];
  for (let i = 0; i < src.length; ) {
    const t = stack[stack.length - 1];
    const c = src[i];

    if (t.k === "str" || t.k === "tpl") {
      if (c === "\\") { emit(c, !keepStrings); emit(src[i + 1] ?? "", !keepStrings); i += 2; continue; }
      if (c === (t.k === "tpl" ? "`" : t.q)) { out += c; i++; stack.pop(); continue; }   // the delimiter itself stays
      if (t.k === "tpl" && c === "$" && src[i + 1] === "{") {   // interpolation: back to CODE until the matching }
        out += "${"; i += 2; stack.push({ k: "code", braces: 0 }); continue;
      }
      emit(c, !keepStrings); i++; continue;
    }

    // code frame
    if (c === "/" && src[i + 1] === "/") { while (i < src.length && src[i] !== "\n") { emit(src[i], true); i++; } continue; }
    if (c === "/" && src[i + 1] === "*") {
      const e = src.indexOf("*/", i + 2);
      const end = e < 0 ? src.length : e + 2;
      for (; i < end; i++) emit(src[i], true);
      continue;
    }
    if (c === '"' || c === "'") { out += c; i++; stack.push({ k: "str", q: c }); continue; }
    if (c === "`") { out += c; i++; stack.push({ k: "tpl" }); continue; }
    if (c === "/" && regexStartsHere(src, i)) {           // a REGEX literal, not division — skip it whole
      out += c; i++;
      for (let cls = false; i < src.length; i++) {
        if (src[i] === "\\") { out += "  "; i++; continue; }
        if (src[i] === "[") cls = true; else if (src[i] === "]") cls = false;
        const done = src[i] === "/" && !cls;
        out += src[i] === "\n" ? "\n" : (done ? "/" : " ");
        if (done || src[i] === "\n") { i++; break; }       // a newline means it was division after all — bail
      }
      continue;
    }
    if (!t.root) {
      if (c === "{") { t.braces++; out += c; i++; continue; }
      if (c === "}") { out += c; i++; if (t.braces === 0) stack.pop(); else t.braces--; continue; }
    }
    out += c; i++;
  }
  return out;
}
function inEngineCode(lit) {
  return engineCode.includes(`"${lit}"`) || engineCode.includes(`'${lit}'`) || engineCode.includes("`" + lit + "`");
}

// --- shared data indexes: loaded ONCE, here, so every later pass reads the SAME parsed data ----
// instead of re-hitting the filesystem — which is what six of the seven authored-overlay walks
// and most of the adversary walks used to do, several of them via a silent `catch (e) { continue;
// }` that made a broken JSON file invisible to the passes built on it: they simply reported
// SUCCESS on a file they never read. A parse failure is now reported HERE, once, loudly (via
// loadJson's throw), and every downstream pass just finds that file's entries absent from the
// index rather than getting a false "clean" read of its own.
const AUTHORED_DOCS = [];    // [{ file, rel, doc }] — one entry per data/authored/*.json file
const AUTHORED_ENTRIES = []; // [{ file, rel, talentName, talent }] — one entry per talent therein
for (const file of fs.readdirSync(AUTHORED_DIR).filter((f) => f.endsWith(".json")).sort()) {
  const rel = `data/authored/${file}`;
  let doc;
  try { doc = loadJson(rel); }
  catch (e) { err(`${rel}: invalid JSON — ${e.message}`); continue; }
  AUTHORED_DOCS.push({ file, rel, doc });
  for (const [talentName, talent] of Object.entries(doc.talents || {})) {
    AUTHORED_ENTRIES.push({ file, rel, talentName, talent });
  }
}
// data/adversaries.json — loaded once the same way. ADVERSARY_ENTRIES simply stays empty (rather
// than throwing further) on a parse failure, so every later pass finds nothing to check — exactly
// what the "reported by the earlier adversaries.json pass" comments below already assumed, now
// literally true instead of assumed.
let ADVERSARY_DATA = null;
const ADVERSARY_ENTRIES = []; // [{ advName, adv, item }]
try { ADVERSARY_DATA = loadJson(ADV_REL); }
catch (e) { err(`${ADV_REL}: invalid JSON — ${e.message}`); }
if (ADVERSARY_DATA) {
  for (const [advName, adv] of Object.entries(ADVERSARY_DATA)) {
    if (advName.startsWith("_")) continue;
    for (const item of adv.items || []) ADVERSARY_ENTRIES.push({ advName, adv, item });
  }
}

// --- pass 1+2: authored files -------------------------------------------------
const talentNames = new Set();
for (const { rel, doc } of AUTHORED_DOCS) {
  for (const k of Object.keys(doc)) if (!TOP_KEYS.has(k)) err(`${rel}: unexpected top-level key "${k}"`);
  for (const [name, t] of Object.entries(doc.talents || {})) {
    talentNames.add(name);
    for (const k of Object.keys(t)) {
      if (!TALENT_KEYS.has(k)) err(`${rel} (${name}): key "${k}" outside the authored-overlay whitelist [${[...TALENT_KEYS].join(", ")}]`);
    }
    for (const [evId, ev] of Object.entries(t.events || {})) {
      // The system's event-rule `id` is a Foundry DocumentIdField — anything that isn't exactly
      // 16 alphanumeric chars fails document validation and the rule is SILENTLY dropped (the
      // 07-12 pass-3b Cruel Step bug: "CruelStepMove01" was 15 chars and the talent went inert).
      if (!/^[a-zA-Z0-9]{16}$/.test(evId)) {
        err(`${rel} (${name}) event ${evId}: rule id must be exactly 16 alphanumeric chars (Foundry DocumentIdField) — the system silently drops invalid rules`);
      }
      if (ev?.id !== evId) {
        err(`${rel} (${name}) event ${evId}: inner "id" (${ev?.id}) doesn't match the rule key`);
      }
      const evName = ev?.event;
      if (typeof evName === "string" && evName) {
        if (evName.startsWith("edha-")) {
          if (!inEngine(evName)) err(`${rel} (${name}) event ${evId}: event "${evName}" has no dispatch site in register-skills.js`);
        } else if (NATIVE_EVENTS && !NATIVE_EVENTS.has(evName)) {
          err(`${rel} (${name}) event ${evId}: event "${evName}" is neither an edha-* event nor one the cosmere-rpg system registers ` +
              `(native: ${[...NATIVE_EVENTS].sort().join(", ")}). A typo here fails SILENTLY at the table.`);
        }
      }
      const h = ev?.handler || {};
      const type = h.type;
      if (typeof type === "string" && type) {
        if (type.startsWith("edha-")) {
          if (!inEngine(type)) err(`${rel} (${name}) event ${evId}: handler type "${type}" has no dispatch site in register-skills.js`);
        } else if (NATIVE_HANDLERS && !NATIVE_HANDLERS.has(type)) {
          err(`${rel} (${name}) event ${evId}: handler type "${type}" is neither an edha-* handler nor one the cosmere-rpg system registers ` +
              `(native: ${[...NATIVE_HANDLERS].sort().join(", ")}). A typo here fails SILENTLY at the table.`);
        }
      }
      if (typeof h.kind === "string" && h.kind && !inEngine(h.kind)) {
        err(`${rel} (${name}) event ${evId}: handler kind "${h.kind}" is not consumed anywhere in register-skills.js`);
      }
      if (typeof h.statusId === "string" && h.statusId && !inEngine(h.statusId)) {
        err(`${rel} (${name}) event ${evId}: statusId "${h.statusId}" is unknown to register-skills.js (typo?)`);
      }
    }
  }
}

